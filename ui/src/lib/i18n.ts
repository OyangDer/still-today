const tables: Record<Lang, Record<Key, string>> = { zh, en };

let lang: Lang = 'zh';
export const setLang = (value: Lang) => (lang = value);
export const currentLang = () => lang;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return tables[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

const WEEKDAYS: Record<Lang, string[]> = {
  zh: ['周一', '周二', '周三', '周四', '周五', '周六', '周日'],
  en: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
};
const WEEKDAYS_LONG: Record<Lang, string[]> = {
  zh: ['星期一', '星期二', '星期三', '星期四', '星期五', '星期六', '星期日'],
  en: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'],
};
const MONTHS_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTHS_EN_LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export const weekdayShort = (d: Date) => WEEKDAYS[lang][weekdayMon(d)];
export const weekdayLong = (d: Date) => WEEKDAYS_LONG[lang][weekdayMon(d)];
export const weekdayHeaders = () => WEEKDAYS[lang].map((w) => (lang === 'zh' ? w.slice(1) : w.slice(0, 2)));

export function monthDay(d: Date): string {
  return lang === 'zh' ? `${d.getMonth() + 1}月${d.getDate()}日` : `${MONTHS_EN[d.getMonth()]} ${d.getDate()}`;
}

/** "9月24日，星期四" / "Thursday, Sep 24". */
export function longDate(d: Date): string {
  return lang === 'zh' ? `${monthDay(d)}，${weekdayLong(d)}` : `${weekdayLong(d)}, ${monthDay(d)}`;
}

/** The part of the day beside the 24-hour clock: 上午/下午/晚上, or am/pm. */
export function dayPart(d: Date): string {
  const h = d.getHours();
  if (lang === 'en') return h < 12 ? 'am' : 'pm';
  return h < 5 ? '凌晨' : h < 11 ? '上午' : h < 13 ? '中午' : h < 18 ? '下午' : '晚上';
}

/** A clock time today; a date and time on any other day. */
export function timeOrDate(d: Date, now: Date): string {
  return daysBetween(d, now) === 0 ? hhmm(d) : `${monthDay(d)} ${hhmm(d)}`;
}

export function monthTitle(d: Date): string {
  return lang === 'zh' ? `${d.getFullYear()}年${d.getMonth() + 1}月` : `${MONTHS_EN_LONG[d.getMonth()]} ${d.getFullYear()}`;
}

/** How long ago, the way a feed says it; past a week, the date. */
export function ago(then: Date, now: Date): string {
  const minutes = Math.floor((now.getTime() - then.getTime()) / 60_000);
  if (minutes < 1) return t('ago.now');
  if (minutes < 60) return t('ago.minutes', { n: minutes });
  if (minutes < 24 * 60 && then.getDate() === now.getDate()) return t('ago.hours', { n: Math.floor(minutes / 60) });
  const days = daysBetween(then, now);
  if (days <= 1) return t('ago.yesterday');
  return days < 7 ? t('ago.days', { n: days }) : monthDay(then);
}

export function duration(seconds: number): string {
  if (seconds < 60) return lang === 'zh' ? `${Math.round(seconds)} 秒` : `${Math.round(seconds)} s`;
  const total = Math.round(seconds / 60);
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (lang === 'zh') return h ? (m ? `${h} 小时 ${m} 分钟` : `${h} 小时`) : `${m} 分钟`;
  return h ? (m ? `${h} h ${m} min` : `${h} h`) : `${m} min`;
}

export type Tone = 'overdue' | 'soon' | 'normal';

/** A due label that reads like a person would say it, plus how urgent it is. */
export function dueLabel(due: Date, now: Date, timed = true): { text: string; tone: Tone } {
  const ms = due.getTime() - now.getTime();
  const days = daysBetween(now, due);
  const time = timed ? hhmm(due) : '';
  if (ms < 0) {
    const late = daysBetween(due, now);
    return { text: late >= 1 ? t('due.overdueDays', { n: late }) : t('due.overdue'), tone: 'overdue' };
  }
  if (timed && ms < HOUR) return { text: t('due.minutes', { n: Math.max(1, Math.round(ms / MINUTE)) }), tone: 'soon' };
  if (timed && ms < 6 * HOUR) return { text: t('due.hours', { n: Math.round(ms / HOUR) }), tone: 'soon' };
  if (days === 0) return { text: t('due.today', { t: time }).trim(), tone: 'soon' };
  if (days === 1) return { text: t('due.tomorrow', { t: time }).trim(), tone: 'soon' };
  if (days < 7) return { text: t('due.weekday', { w: weekdayShort(due), t: time }).trim(), tone: 'normal' };
  return { text: monthDay(due), tone: 'normal' };
}
